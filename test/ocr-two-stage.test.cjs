// เทสต์การทำความสะอาดข้อความของ Two-Stage Localized OCR
//
// ข้อมูลตั้งต้นมาจากหน้าเอกสารจริง (ใบเบิกเงินที่สแกน) — เน้นว่า
//   - คำไทย/ตัวเลข/ข้อความจริงต้องไม่ถูกแก้
//   - เศษอักขระเดี่ยวจากโลโก้ เส้นตาราง และลายเซ็นต้องถูกตัดออก
//
// รันด้วย: npm test
'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');

const { cleanText } = require('../src/main/ocr-two-stage.cjs');

test('คงคำไทยจริง ตัวเลข และรหัสไว้ครบ', function () {
    const unchanged = [
        'หนังสือรับรองการหักภาษี ณ ที่จ่าย',
        'จำนวน 3 รายการ',
        'ผู้ตรวจสอบ 1',
        'หน้า 1 จาก 1',
        'ข้อ ก และ ข้อ ข',
        'แบบ ก',
        'มหาวิทยาลัยทักษิณ',
        'วันที่ 25/10/2569',
        'ค่าธรรมเนียม',
        'RC05000000270100046',
        'AP05000000270100045',
        'PR108',
        '1,234.50',
        '0.00'
    ];

    unchanged.forEach(function (input) {
        assert.equal(cleanText(input), input);
    });
});

test('ตัดอักขระไทย/ละตินเดี่ยวที่หลุดมากลางบรรทัด', function () {
    assert.equal(
        cleanText('เรียน.ผูอานวยก: บ๐ เสาธตมหาวทยาลัยทักษณ ฝายมัธยม'),
        'เรียน.ผูอานวยก: เสาธตมหาวทยาลัยทักษณ ฝายมัธยม'
    );

    assert.equal(
        cleanText('อนุมัติให้เบิกจ่ายได้ ผ ล ๑ บ D บ'),
        'อนุมัติให้เบิกจ่ายได้'
    );

    assert.equal(
        cleanText('เห็นควรให้ ิ ว่าไ 8 ศ บ'),
        'เห็นควรให้ ว่าไ 8'
    );

    assert.equal(
        cleanText('โลโก้ บ๐ ปนข้อความ'),
        'โลโก้ ปนข้อความ'
    );

    assert.equal(
        cleanText('ลายเซ็น D e ปน'),
        'ลายเซ็น ปน'
    );
});

test('ตัดเศษท้ายบรรทัดที่มาจากลายเซ็นและเส้นตาราง', function () {
    assert.equal(
        cleanText('ผู้อำนวยการโรงเรียนส่าธิตมหาวิทยาลัยทักษิณ ฝ่ายมัธยม บ'),
        'ผู้อำนวยการโรงเรียนส่าธิตมหาวิทยาลัยทักษิณ ฝ่ายมัธยม'
    );

    assert.equal(cleanText('รหัสบัญชี e e'), 'รหัสบัญชี');
    assert.equal(
        cleanText('นักวิชาการเงิน์และบัญชี - e'),
        'นักวิชาการเงิน์และบัญชี'
    );
    assert.equal(
        cleanText('วันที่.1.4/10/2569. e'),
        'วันที่.1.4/10/2569'
    );
});

test('ตัวเลขเดี่ยวท้ายบรรทัดยังคงอยู่ (กันข้อมูลจริงหาย)', function () {
    // ตัวเลขท้ายบรรทัดอาจเป็นค่าจริง (ผู้ตรวจสอบ 1, หน้า 1) หรือเศษจากลายเซ็น
    // จึงตั้งใจไม่ตัดอัตโนมัติ — เทสต์นี้ล็อกพฤติกรรมไว้
    const unchanged = [
        'หัวหน้าสำนักงาน 0',
        'จ่ายให้แก่..นายกฤษฎ. พัชรสิทธิ์.(ธนาคารไทยพาณิชย์.จำกัด..มหาชน.4064268953) 0',
        'การสอนด้านวิทยาศาสตร์และเทคโ 9',
        'เห็นควรให้ ว่าไ 8',
        'ผู้ตรวจสอบ 1',
        'จำนวน 3 รายการ',
        'หน้า 1 จาก 1',
        '1,234.50'
    ];

    unchanged.forEach(function (input) {
        assert.equal(cleanText(input), input);
    });
});

test('ไม่แตะข้อความอังกฤษล้วน', function () {
    const unchanged = [
        'Invoice number 12345 dated 25/10/2026',
        'Total amount 9,999 THB',
        'ISO 9001',
        'ymp'
    ];

    unchanged.forEach(function (input) {
        assert.equal(cleanText(input), input);
    });
});

test('ยุบช่องว่างซ้ำและตัดช่องว่างหัวท้าย', function () {
    assert.equal(
        cleanText('  ทดสอบ   หลาย   ช่องว่าง  '),
        'ทดสอบ หลาย ช่องว่าง'
    );
});

test('บรรทัดที่มีแต่เศษขยะกลายเป็นข้อความว่าง', function () {
    assert.equal(cleanText('Pเร'), '');
    assert.equal(cleanText(''), '');
});
